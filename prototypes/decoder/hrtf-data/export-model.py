"""The two-input model for the match prototype: patterns and baseline as spherical harmonics, so any direction works.

pattern-models.py saves the VAE's notch patterns on a grid of its respaced axis and the population baseline, on 300
directions over the sphere and 61 in the median plane, on the ERB axis. Here each is fitted with spherical harmonics on
the 300 (the roughness penalty of the grid experiments), the order chosen by the error on the 61 the fit never saw.

Writes the model as JavaScript, outside version control: it is derived from SONICOM data, whose licence is unclear.

A two-free-input model (pattern-models3.py) is a grid over both inputs; it is thinned to every second point (13 x 13)
to keep the file small, and the page interpolates between neighbours.

  python export-model.py <...-model.npz> <out.js>                 the one-input model with a shift
  python export-model.py <...-models3.npz> <out.js> <variant>     a two-input model, e.g. V2b
"""
import base64, os, sys
from importlib.util import spec_from_file_location, module_from_spec
import numpy as np

_d = os.path.dirname(os.path.abspath(__file__))
_s = spec_from_file_location("ge", os.path.join(_d, "grid-experiment.py")); ge = module_from_spec(_s); _s.loader.exec_module(ge)
_s = spec_from_file_location("bf", os.path.join(_d, "..", "listen", "build-filters.py")); bf = module_from_spec(_s); _s.loader.exec_module(bf)
ORDERS = (8, 10, 12, 15)
LAM = 1e-4


def main(path, out, variant=None):
    m = np.load(path)
    az, el, sphere = m["az"], m["el"], m["sphere"]
    med = np.setdiff1d(np.arange(len(az)), sphere)
    if variant:
        g = m[f"{variant}_grid"].astype(float).reshape(25, 25, len(az), -1)[::2, ::2]   # 13 x 13 x dirs x E
        zz = m[f"{variant}_z"].reshape(25, 25, 2)[::2, ::2]
        lo, hi = zz[0, 0], zz[-1, -1]
        fitted = (m[f"{variant}_fitted"] - lo) / (hi - lo)                              # held-out heads, 0…1 on the pad
        pats, base = g.reshape(-1, len(az), g.shape[-1]), m["base"].astype(float)
        kind = {"grid": [13, 13], "fitted": np.round(fitted, 3).tolist()}
    else:
        pats, base = m["patterns"].astype(float), m["baseline"].astype(float)          # T x dirs x E, dirs x E
        kind = None
    w = np.full(len(sphere), 1 / len(sphere))
    allv = np.concatenate([pats, base[None]])                                       # (T+1) x dirs x E
    chosen = None
    for order in ORDERS:
        y = ge.sh_orth(order, az[sphere], el[sphere])
        ym = ge.sh_orth(order, az[med], el[med])
        c = np.stack([ge.solve(y, w, v[sphere], LAM, order) for v in allv])         # (T+1) x coefs x E
        err = np.sqrt(np.mean((np.einsum("dc,tce->tde", ym, c) - allv[:, med]) ** 2))
        print(f"order {order:2d}: error on the median plane the fit never saw {err:.2f} dB RMS")
        if chosen is None and err < 0.5:
            chosen = (order, c, err)
    if chosen is None:
        chosen = (ORDERS[-1], c, err)
    order, c, err = chosen
    print(f"using order {order} ({err:.2f} dB)")
    # The browser's SH must be these: check the JavaScript convention against one direction later (sh_sn3d scaled).
    blob = lambda a: base64.b64encode(np.ascontiguousarray(a, dtype="<f4").tobytes()).decode()
    with open(out, "w") as js:
        js.write("// Generated by prototypes/decoder/hrtf-data/export-model.py — not under version control (trained in part on\n")
        js.write("// SONICOM data, licence unclear). The two-input model of the CLL's direction cues: pattern t (0…1) and shift s\n")
        js.write("// (ERB). Patterns: [t][coef][erb] and baseline [coef][erb], orthonormal real SH (SN3D·sqrt((2n+1)/4π)), ACN.\n")
        # A property of window, not a const: a page checks for it with window.MODEL, which a failed or missing
        # file leaves simply undefined.
        if kind:
            js.write(f"window.MODEL = {{ order: {order}, grid: {kind['grid']}, variant: \"{variant}\",\n")
            js.write(f"  erb: {np.round(m['erb'], 4).tolist()},\n  freq: {np.round(m['freq'], 2).tolist()},\n")
            js.write(f"  fitted: {kind['fitted']},\n")
        else:
            js.write(f"window.MODEL = {{ order: {order}, t: {np.round(m['t'], 6).tolist()},\n")
            js.write(f"  erb: {np.round(m['erb'], 4).tolist()},\n  freq: {np.round(m['freq'], 2).tolist()},\n")
            js.write(f"  shiftMin: {float(m['shifts'][0])}, shiftMax: {float(m['shifts'][-1])},\n")
            js.write(f"  fitted: {np.round(m['fitted'], 3).tolist()},\n")
        js.write(f"  patterns: \"{blob(c[:-1])}\",\n  baseline: \"{blob(c[-1])}\" }};\n")
    print(f"written {out}: {os.path.getsize(out) / 1e6:.1f} MB")
    # Reference values for checking the browser: one direction, two (t, s).
    y1 = ge.sh_orth(order, np.array([0.5]), np.array([0.3]))[0]
    for ti in (10, 30):
        print(f"  check: az 0.5 rad, el 0.3 rad, t index {ti}: pattern at erb index 40 = {y1 @ c[ti][:, 40]:.4f}, baseline = {y1 @ c[-1][:, 40]:.4f}")


if __name__ == "__main__":
    main(*sys.argv[1:])

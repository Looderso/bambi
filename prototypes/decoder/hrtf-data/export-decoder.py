"""The decoder of pattern-models4.py for the match prototype: its weights, so the browser generates the pattern itself.

No grid and no fit: the page runs the network for the pad's two inputs and gets order-20 SH coefficients for every
point of the ERB axis. Written beside it: the population baseline (order-20 coefficients), the population's average
ILD and ITD (the match page's SN3D coefficients), the latent range the pad spans, and the held-out heads' best places.
Outside version control: trained in part on SONICOM data, whose licence is unclear.

  python export-decoder.py <...-model4.pt> <data set .npz> <out.js>
"""
import base64, os, sys
from importlib.util import spec_from_file_location, module_from_spec
import numpy as np
import torch

_d = os.path.dirname(os.path.abspath(__file__))
_s = spec_from_file_location("p4", os.path.join(_d, "pattern-models4.py")); p4 = module_from_spec(_s); _s.loader.exec_module(p4)


def main(model_path, data_path, out):
    ck = torch.load(model_path, weights_only=False)
    data = np.load(data_path)
    st = {k: v.cpu().numpy().astype(np.float32) for k, v in ck["state"].items()}
    blob = lambda a: base64.b64encode(np.ascontiguousarray(a, dtype="<f4").tobytes()).decode()
    layers = {k: {"shape": list(v.shape), "data": blob(v)} for k, v in st.items() if k.startswith("dec")}
    lo, hi = ck["lo"], ck["hi"]
    fitted = np.round((ck["fitted"] - lo) / (hi - lo), 3).tolist()
    o, io, nb = int(data["order"]), int(data["itd_order"]), int(data["nfft"]) // 2 + 1
    to_sn3d = lambda order: np.array([np.sqrt((2 * n + 1) / (4 * np.pi)) for n in range(order + 1) for _ in range(2 * n + 1)])
    ild = data["grand_mean"].astype(float)[:, nb:] * to_sn3d(o)[:, None]
    itd = data["itd_grand_mean"].astype(float) * to_sn3d(io)
    with open(out, "w") as js:
        js.write("// Generated by prototypes/decoder/hrtf-data/export-decoder.py — not under version control (trained in part on\n")
        js.write("// SONICOM data, licence unclear). The two-input model's decoder: inputs (0…1 on the pad) → order-20 orthonormal SH\n")
        js.write("// coefficients of the CLL's notch layer for every ERB point; the population baseline in the same form.\n")
        js.write(f"window.MODEL = {{ kind: \"decoder\", order: {p4.ORDER}, scale: {p4.SCALE}, hidden: 128, length: {len(p4.ex.ERB)},\n")
        js.write(f"  erb: {np.round(p4.ex.ERB, 4).tolist()},\n  lo: {np.round(lo, 6).tolist()}, hi: {np.round(hi, 6).tolist()},\n")
        js.write(f"  fitted: {fitted},\n")
        js.write(f"  layers: {{ {', '.join(f'{repr(k)}: {{ shape: {v["shape"]}, data: \"{v["data"]}\" }}' for k, v in layers.items())} }},\n")
        js.write(f"  baseline: \"{blob(ck['base_c'])}\",\n")
        js.write(f"  populationIld: \"{blob(ild)}\", populationIldOrder: {o},\n  populationItd: \"{blob(itd)}\", populationItdOrder: {io} }};\n")
    print(f"written {out}: {os.path.getsize(out) / 1e6:.1f} MB; {sum(np.prod(v['shape']) for v in layers.values()) / 1e3:.0f} k decoder weights")
    # Reference for checking the browser: the decoder at the pad's middle.
    model = p4.SHNet(961, len(p4.ex.ERB), 2, 128)
    model.load_state_dict(ck["state"]); model.eval()
    z = torch.tensor([(lo + hi) / 2], dtype=torch.float32)
    with torch.no_grad():
        c = model.decode(z).numpy()[0] * p4.SCALE                      # NC x E
    print(f"  check, pad middle: coefficient 0 at ERB index 40 = {c[0, 40]:.5f}, coefficient 5 = {c[5, 40]:.5f}, "
          f"coefficient 300 at ERB index 70 = {c[300, 70]:.5f}")


if __name__ == "__main__":
    main(*sys.argv[1:])
